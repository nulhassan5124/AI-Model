# Classify drinks into calorie ranges
def categorize_calories(cal):
    if cal == 0:
        return '0 kcal (Calorie-Free)'
    elif cal <= 100:
        return 'Low Calorie (1-100 kcal)'
    elif cal <= 250:
        return 'Moderate Calorie (101-250 kcal)'
    else:
        return 'High Calorie (>250 kcal)'

